"""Render metric documentation from the registry (CLAUDE.md section 35).

``docs/metric_catalog.md`` and ``docs/interpretation/<metric_id>.md`` are
generated by ``scripts/generate_docs.py`` from these functions, and a test
fails when the committed files are stale, so documentation cannot drift from
the code.
"""

from __future__ import annotations

from openfactsheet.metrics.registry import all_metrics
from openfactsheet.models.metric import CATEGORY_TITLES, MetricDefinition
from openfactsheet.policy.methodology_version import METHODOLOGY_VERSION
from openfactsheet.policy.thresholds import get_policy

GENERATED_NOTE = (
    "<!-- Generated by scripts/generate_docs.py from the metric registry. Do not edit by hand. -->"
)

_DIRECTION = {
    "higher_is_better": "Higher is better",
    "lower_is_better": "Lower is better",
    "context_dependent": "Context dependent",
    "neutral": "Neutral (descriptive)",
}

_ASSUMPTION_LABELS = {
    "annualization": "annualization factor",
    "risk_free": "risk-free = 0",
    "mar": "MAR = 0",
    "omega_threshold": "threshold = 0",
    "tail": "95% confidence",
    "drawdown": "wealth starts at 1",
    "sample_std": "sample std (n-1)",
    "benchmark": "supplied benchmark",
    "regression": "OLS",
}


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _references_summary(d: MetricDefinition) -> str:
    parts = []
    for ref in d.docs.reference_implementations:
        library = ref.library.split(" ")[0]
        parts.append(f"{library} {'✓' if ref.agrees else '≠'}")
    return ", ".join(parts) or "—"


def render_catalog() -> str:
    lines = [
        GENERATED_NOTE,
        "",
        "# Metric catalog",
        "",
        f"Canonical metrics of OpenFactsheet methodology {METHODOLOGY_VERSION}. Every report "
        "computes all of them; a metric that cannot be computed is reported with a status and a "
        "reason, never omitted.",
        "",
        "Reference column: ✓ agrees with the OpenFactsheet convention, ≠ documented convention "
        "difference (see [reference implementations](validation/reference_implementations.md)).",
        "",
    ]
    for category, title in CATEGORY_TITLES.items():
        rows = [d for d in all_metrics() if d.category == category]
        if not rows:
            continue
        lines += [
            f"## {title}",
            "",
            "| ID | Name | Nature | Unit | Direction | Benchmark | Annualized | "
            "Canonical parameters | Minimum-data policy | Status | References |",
            "|---|---|---|---|---|---|---|---|---|---|---|",
        ]
        for d in rows:
            params = ", ".join(_ASSUMPTION_LABELS[k] for k in d.assumption_keys) or "—"
            lines.append(
                f"| [`{d.id}`](interpretation/{d.id}.md) | {_cell(d.name)} | {d.nature} | "
                f"{d.unit} | {_DIRECTION[d.direction]} | {'yes' if d.requires_benchmark else 'no'} "
                f"| {'yes' if d.annualized else 'no'} | {params} | `{d.min_data_policy}` | "
                f"implemented ({d.formula_id}) | {_references_summary(d)} |"
            )
        lines.append("")
    return "\n".join(lines)


def render_metric_page(d: MetricDefinition) -> str:
    docs = d.docs
    policy = get_policy(d.min_data_policy)

    def bullets(items: tuple[str, ...]) -> list[str]:
        return [f"- {item}" for item in items] if items else ["- None beyond the general inputs."]

    lines = [
        GENERATED_NOTE,
        "",
        f"# {d.name} (`{d.id}`)",
        "",
        f"*Category: {CATEGORY_TITLES[d.category]} · Nature: {d.nature} · Unit: {d.unit} · "
        f"Formula id: `{d.formula_id}` · Methodology {METHODOLOGY_VERSION}*",
        "",
        "## 1. What does it measure?",
        "",
        docs.measures,
        "",
        "## 2. Formula",
        "",
        "```text",
        docs.formula,
        "```",
        "",
        "## 3. Required inputs",
        "",
        docs.inputs + (" A benchmark is required." if d.requires_benchmark else ""),
        "",
        "## 4. Is higher or lower better?",
        "",
        _DIRECTION[d.direction] + ".",
        "",
        "## 5. Plain-language interpretation",
        "",
        docs.retail,
        "",
        "## 6. Professional interpretation",
        "",
        docs.institutional,
        "",
        "## 7. Assumptions",
        "",
        *bullets(docs.assumptions),
        "",
        "## 8. When can it be misleading?",
        "",
        *bullets(docs.misleading_when),
        "",
        "## 9. Minimum sensible data",
        "",
        f"{docs.minimum_data} (policy `{policy.key}`: {policy.description})",
        "",
        "## 10. Reference implementations",
        "",
    ]
    if docs.reference_implementations:
        lines += ["| Library | Function | Agrees | Note |", "|---|---|---|---|"]
        for ref in docs.reference_implementations:
            lines.append(
                f"| {_cell(ref.library)} | `{_cell(ref.function)}` | "
                f"{'yes' if ref.agrees else 'no (documented difference)'} | {_cell(ref.note)} |"
            )
    else:
        lines.append("No established library implementation was identified.")
    lines += ["", "## 11. Sources", ""]
    lines += [f"- {ref.citation}" + (f" <{ref.url}>" if ref.url else "") for ref in docs.references]
    lines += ["", "## 12. OpenFactsheet convention", "", docs.convention, ""]
    return "\n".join(lines)


def render_all() -> dict[str, str]:
    """Map of repository-relative path to generated content."""
    files = {"docs/metric_catalog.md": render_catalog()}
    for d in all_metrics():
        files[f"docs/interpretation/{d.id}.md"] = render_metric_page(d)
    return files
