def _get(path: str) -> Any:
    return canonical_methodology().get(path)


def _pct(x: Any) -> str:
    return f"{float(x):.0%}"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _math(latex: str) -> list[str]:
    return ["```math", latex, "```"]


def _ppy_table() -> str:
    table = _get("annualization.periods_per_year")
    return ", ".join(f"{k.replace('_', ' ')} {v:g}" for k, v in table.items())


